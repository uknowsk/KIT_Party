  var n = 0;
  Txn make(_Row r, TxnType type) => Txn(
        id: 'seed_${n++}',
        date: DateTime(2026, r.$1, 1),
        type: type,
        category: r.$2,
        item: r.$3,
        amount: r.$4,
        memberId: r.$5 == null ? null : memberIdOf(r.$5!),
      );
